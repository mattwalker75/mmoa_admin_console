// helpers/dbSchema.js — live-schema introspection shared by the Data
// Browser (routes/dataBrowser.js) and Backup/Restore (routes/backup.js).
//
// Why this exists: both pages build SQL whose IDENTIFIERS (table and column
// names) vary at runtime. Identifiers can't be bound as `?` parameters, so
// the rule is: an identifier only ever comes from THIS module — i.e. from
// the live database's own catalog (sqlite_master / PRAGMA table_info on
// SQLite, information_schema on MySQL) — and never from a URL, a form field,
// or an uploaded file. Callers look a user-supplied name up in the list this
// module returns and use the catalog's copy; anything not found is refused.
// Values are always bound as parameters.
//
// Works for all three engines the console supports:
//   * local SQLite   (db/database.js → sqlite3 driver)
//   * remote SQLite  (db/remoteSqlite.js → sqlite3 CLI over SSH / SSM;
//                     PRAGMA output comes back through `sqlite3 -json`)
//   * MySQL          (db/database.js → mysql2 pool; DATABASE() is the
//                     configured schema)
//
// Results are NOT cached: the web app migrates its own schema at boot, and a
// stale column list would make the Data Browser refuse (or worse, mis-map) a
// column that now exists. Introspection is a couple of cheap catalog queries.

// Quote an identifier for either engine. Backticks are accepted by both
// MySQL and SQLite. Only ever applied to names that came from the catalog.
function quoteIdent(name) {
  return '`' + String(name).replace(/`/g, '``') + '`';
}

// Every user table, sorted by name. SQLite's internal sqlite_* tables are
// excluded (sqlite_sequence etc. are engine bookkeeping, not app data).
async function listTables(db) {
  if (db.engine === 'mysql') {
    const rows = await db.allAsync(
      "SELECT table_name AS name FROM information_schema.tables WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE' ORDER BY table_name", []);
    return rows.map(r => r.name || r.NAME || r.TABLE_NAME).filter(Boolean);
  }
  const rows = await db.allAsync(
    "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name", []);
  return rows.map(r => r.name).filter(Boolean);
}

// Column metadata for one table, in declaration order:
//   [{ name, type, notnull, dflt, pk (1-based position in the primary key,
//      0 = not part of it), auto (value generated by the engine on insert) }]
// `table` MUST already be a catalog name (see resolveTable below).
async function describeTable(db, table) {
  if (db.engine === 'mysql') {
    const rows = await db.allAsync(
      `SELECT column_name AS name, column_type AS type, is_nullable AS nullable,
              column_default AS dflt, column_key AS ckey, extra AS extra
         FROM information_schema.columns
        WHERE table_schema = DATABASE() AND table_name = ?
        ORDER BY ordinal_position`, [table]);
    // Primary-key order comes from key_column_usage (column_key only says
    // "PRI", not the position within a composite key).
    const pkRows = await db.allAsync(
      `SELECT column_name AS name, ordinal_position AS pos
         FROM information_schema.key_column_usage
        WHERE table_schema = DATABASE() AND table_name = ? AND constraint_name = 'PRIMARY'
        ORDER BY ordinal_position`, [table]);
    const pkPos = new Map(pkRows.map(r => [r.name, Number(r.pos) || 0]));
    return rows.map(r => ({
      name: r.name,
      type: String(r.type || ''),
      notnull: String(r.nullable).toUpperCase() === 'NO',
      dflt: r.dflt == null ? null : r.dflt,
      pk: pkPos.get(r.name) || 0,
      auto: /auto_increment/i.test(String(r.extra || ''))
    }));
  }
  // PRAGMA can't be parameterized; `table` is a real, already-discovered name.
  const rows = await db.allAsync(`PRAGMA table_info(${quoteIdent(table)})`, []);
  const pkCount = rows.filter(r => Number(r.pk) > 0).length;
  return rows.map(r => {
    const type = String(r.type || '');
    const pk = Number(r.pk) || 0;
    return {
      name: r.name,
      type,
      notnull: Number(r.notnull) === 1,
      dflt: r.dflt_value == null ? null : r.dflt_value,
      pk,
      // A single-column INTEGER PRIMARY KEY is an alias for the rowid: SQLite
      // assigns it on insert when the value is omitted.
      auto: pk > 0 && pkCount === 1 && /^INTEGER$/i.test(type.trim())
    };
  });
}

// Look a caller-supplied table name up in the live catalog. Returns the
// catalog's spelling, or null when no such table exists. Exact match only.
async function resolveTable(db, name) {
  const tables = await listTables(db);
  const want = String(name == null ? '' : name);
  return tables.find(t => t === want) || null;
}

// Primary-key columns of a described table, in key order.
function primaryKey(columns) {
  return columns.filter(c => c.pk > 0).sort((a, b) => a.pk - b.pk);
}

// Password / token hash columns: shown masked and never writable from the
// generic editors (use Nonprofits → Reset password, which bcrypts properly).
function isHashColumn(name) {
  return /password_hash/i.test(name) || /_hash$/i.test(name);
}

// Columns worth searching with LIKE: textual declared types. SQLite columns
// with no declared type are included (they hold whatever was written).
function isTextColumn(col) {
  const t = String(col.type || '').toLowerCase();
  if (!t) return true;
  return /char|text|clob|enum|set|json/.test(t);
}

module.exports = {
  quoteIdent, listTables, describeTable, resolveTable, primaryKey,
  isHashColumn, isTextColumn
};
